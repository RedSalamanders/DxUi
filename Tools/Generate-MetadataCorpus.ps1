<#
.SYNOPSIS Regenerates the independent TOML and YAML metadata validity corpus.
.DESCRIPTION Reads only hash-pinned Git archives. It emits embedded original input bytes and upstream validity expectations;
YAML multi-document cases are marked excluded and the two duplicate-key representation cases are identified explicitly.
.PARAMETER InputDirectory Directory containing the pinned corpus archives.
.PARAMETER OutputPath Output native test header.
.PARAMETER Check Compare generated bytes with the existing header without writing.
.OUTPUTS One generated native header unless Check is used. No network or temporary files are used.
.EXAMPLE
./Tools/Generate-MetadataCorpus.ps1 -Check
#>
[CmdletBinding()]
param(
    [string] $InputDirectory=(Join-Path $PSScriptRoot '../ThirdParty/Markdown/corpora'),
    [string] $OutputPath=(Join-Path $PSScriptRoot '../Tests/Controls/Controls.Tests.MetadataCorpus.h'),
    [switch] $Check
)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
function Read-PinnedArchive([string]$Name,[string]$Hash) {
    $path=Join-Path $InputDirectory $Name
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -cne $Hash) { throw "Pinned metadata corpus differs: $Name" }
    $bytes=[IO.File]::ReadAllBytes($path)
    $entries=@{}
    for ($offset=0; $offset+512 -le $bytes.Length;) {
        if ($bytes[$offset] -eq 0) { break }
        $readField={param($at,$length) [Text.Encoding]::ASCII.GetString($bytes,$offset+$at,$length).Trim([char]0,' ') }
        $name=& $readField 0 100; $prefix=& $readField 345 155
        if ($prefix) { $name="$prefix/$name" }
        $sizeField=& $readField 124 12
        $length=if ($sizeField) { [Convert]::ToInt64($sizeField,8) } else { 0 }
        $type=[char]$bytes[$offset+156]; $start=$offset+512
        if ($length -lt 0 -or $start+$length -gt $bytes.Length) { throw "Invalid archive entry: $name" }
        if ($type -eq '0' -or [int]$type -eq 0) {
            if ($entries.ContainsKey($name)) { throw "Duplicate archive entry: $name" }
            $data=[byte[]]::new([int]$length); [Array]::Copy($bytes,$start,$data,0,[int]$length); $entries[$name]=$data
        }
        $offset=$start+([int][Math]::Ceiling($length/512.0))*512
    }
    return $entries
}
function BytesLiteral([byte[]]$Bytes) {
    $value=[Text.StringBuilder]::new()
    foreach($b in $Bytes) { [void]$value.Append(('\x{0:X2}' -f $b)) }
    return ('std::string_view("{0}", {1}u)' -f $value.ToString(),$Bytes.Length)
}
$toml=Read-PinnedArchive 'toml-test-96fd088/source.tar' '746D1D8B07805B20CE2C0612DC8B7A6FED9653E7D03939DA325FD44B55FC2433'
$yaml=Read-PinnedArchive 'yaml-test-suite-6ad3d2c/source.tar' '8FC549BAB9FC4B1E258C32EA42C484305B81D489A38C858D2EEAA2BEC6828671'
$lines=[Text.Encoding]::UTF8.GetString($toml['tests/files-toml-1.0.0']) -split "`n"
$output=[Text.StringBuilder]::new()
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <string_view>')
[void]$output.AppendLine('// Generated from pinned upstream test archives; run Tools/Generate-MetadataCorpus.ps1.')
[void]$output.AppendLine('namespace MetadataCorpus')
[void]$output.AppendLine('{')
[void]$output.AppendLine('// clang-format off')
[void]$output.AppendLine('enum class Expected { Valid, Invalid, Duplicate, MultiDocument };')
[void]$output.AppendLine('struct Case { std::string_view name, bytes; Expected expected; };')
[void]$output.AppendLine('inline constexpr Case Toml[] = {')
$count=0
foreach($line in $lines){
    $name=$line.TrimEnd("`r"); if(-not $name.EndsWith('.toml',[StringComparison]::Ordinal)){continue}
    $path="tests/$name"; if(-not $toml.ContainsKey($path)){throw "Missing TOML case: $path"}
    $expected=if($name.StartsWith('invalid/',[StringComparison]::Ordinal)){'Invalid'}else{'Valid'}
    [void]$output.AppendLine(('    {{"{0}", {1}, Expected::{2}}},' -f $name,(BytesLiteral $toml[$path]),$expected)); $count++
}
if($count -ne 717){throw "Expected 717 TOML 1.0 cases, got $count"}
[void]$output.AppendLine('};')
[void]$output.AppendLine('inline constexpr Case Yaml[] = {')
$names=[string[]]@($yaml.Keys | Where-Object { $_.EndsWith('/in.yaml',[StringComparison]::Ordinal) })
[Array]::Sort($names,[StringComparer]::Ordinal)
$multi=0
foreach($path in $names){
    $dir=$path.Substring(0,$path.Length-8); $events="$dir/test.event"; $error="$dir/error"
    if(-not $yaml.ContainsKey($events)){throw "Missing YAML events: $events"}
    $eventText=[Text.Encoding]::UTF8.GetString($yaml[$events]); $documents=([regex]::Matches($eventText,'\+DOC')).Count
    $expected=if($documents -gt 1){$multi++;'MultiDocument'}elseif($dir -in @('2JQS','X38W')){'Duplicate'}elseif($yaml.ContainsKey($error)){'Invalid'}else{'Valid'}
    [void]$output.AppendLine(('    {{"{0}", {1}, Expected::{2}}},' -f $dir,(BytesLiteral $yaml[$path]),$expected))
}
if($names.Count -ne 402 -or $multi -ne 20){throw "Expected 402 YAML cases and 20 multi-document exclusions, got $($names.Count)/$multi"}
[void]$output.AppendLine('};')
[void]$output.AppendLine('// clang-format on')
[void]$output.AppendLine('} // namespace MetadataCorpus')
$expected=$output.ToString().Replace("`r`n","`n").Replace("`n","`r`n")
if($Check){if(-not(Test-Path -LiteralPath $OutputPath) -or [IO.File]::ReadAllText($OutputPath) -cne $expected){throw 'Metadata corpus output is missing or stale.'}}
else{[IO.File]::WriteAllText($OutputPath,$expected,[Text.UTF8Encoding]::new($false))}
Write-Host 'Metadata corpus: 717 TOML and 402 YAML cases, including 20 out-of-scope YAML streams.'
