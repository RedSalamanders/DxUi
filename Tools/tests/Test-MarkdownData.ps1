foreach($item in $generators){
    Invoke-FixtureCase "offline reproducibility, read-only checks and stale/missing output for $($item.script)" {
        param($root)
        $script=Join-Path $repository $item.script
        $inputs=Join-Path $repository $item.inputs
        $output=Join-Path $root 'generated.h'
        Assert-Throws { & $script -InputDirectory $inputs -OutputPath $output -Check } 'missing output rejected'
        Assert-True (-not(Test-Path -LiteralPath $output)) 'check never creates output'
        & $script -InputDirectory $inputs -OutputPath $output
        $expected=(Get-FileHash -LiteralPath (Join-Path $repository $item.output)).Hash
        Assert-Equal $expected (Get-FileHash -LiteralPath $output).Hash 'generated bytes match committed header'
        & $script -InputDirectory $inputs -OutputPath $output
        Assert-Equal $expected (Get-FileHash -LiteralPath $output).Hash 'repeat is deterministic'
        $old=[datetime]::new(2020,1,1,0,0,0,[DateTimeKind]::Utc)
        [IO.File]::SetLastWriteTimeUtc($output,$old)
        & $script -InputDirectory $inputs -OutputPath $output -Check
        Assert-Equal $old ([IO.File]::GetLastWriteTimeUtc($output)) 'checking is read only'
        [IO.File]::AppendAllText($output,'// changed')
        $changed=(Get-FileHash -LiteralPath $output).Hash
        Assert-Throws { & $script -InputDirectory $inputs -OutputPath $output -Check } 'stale output rejected'
        Assert-Equal $changed (Get-FileHash -LiteralPath $output).Hash 'stale evidence retained'
    }
    Invoke-FixtureCase "all data and license pins fail closed for $($item.script)" {
        param($root)
        $script=Join-Path $repository $item.script
        $inputs=Join-Path $root 'inputs'
        Copy-Item -LiteralPath (Join-Path $repository $item.inputs) -Destination $inputs -Recurse
        $output=Join-Path $root 'output.h'
        foreach($pin in $item.pins){
            $path=Join-Path $inputs $pin
            $original=[IO.File]::ReadAllBytes($path)
            [IO.File]::AppendAllText($path,' ')
            Assert-Throws { & $script -InputDirectory $inputs -OutputPath $output } "changed $pin fails before output"
            Assert-True (-not(Test-Path -LiteralPath $output)) 'refused input writes no output'
            [IO.File]::WriteAllBytes($path,$original)
            Move-Item -LiteralPath $path -Destination ($path+'.held')
            try{Assert-Throws { & $script -InputDirectory $inputs -OutputPath $output } "missing $pin fails"}
            finally{Move-Item -LiteralPath ($path+'.held') -Destination $path}
            Assert-True (-not(Test-Path -LiteralPath $output)) 'missing input writes no output'
        }
    }
}
Invoke-FixtureCase 'Unicode 17 first-strong tables include defaults and explicit neutral exceptions' {
    param($root)
    $expected=[byte[]]::new(0x110000)
    $lines=[IO.File]::ReadAllLines((Join-Path $repository 'ThirdParty/Unicode/17.0.0/DerivedBidiClass.txt'))
    foreach($line in $lines){
        if($line -match '^# @missing:\s*([0-9A-F]+)\.\.([0-9A-F]+);\s*(\w+)'){
            $first=[Convert]::ToInt32($Matches[1],16);$last=[Convert]::ToInt32($Matches[2],16)
            $class=switch($Matches[3]){'Left_To_Right'{1}'Right_To_Left'{2}'Arabic_Letter'{2}'European_Terminator'{0}default{throw 'Unexpected bidi default'}}
            [Array]::Fill($expected,[byte]$class,$first,$last-$first+1)
        }
    }
    foreach($line in $lines){
        if($line -match '^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Z]+)\s*#'){
            $first=[Convert]::ToInt32($Matches[1],16);$last=if($Matches[2]){[Convert]::ToInt32($Matches[2],16)}else{$first}
            $class=if($Matches[3] -eq 'L'){1}elseif($Matches[3] -in @('R','AL')){2}else{0}
            [Array]::Fill($expected,[byte]$class,$first,$last-$first+1)
        }
    }
    $actual=[byte[]]::new($expected.Length);$class=0
    foreach($line in [IO.File]::ReadLines((Join-Path $repository 'src/Controls/DxUi.MarkdownUnicodeData.h'))){
        if($line -eq 'inline constexpr Range kBidiL[] = {'){$class=1;continue}
        if($line -eq 'inline constexpr Range kBidiR[] = {'){$class=2;continue}
        if($class -and $line -eq '};'){$class=0;continue}
        if($class -and $line -match '^\{0x([0-9A-F]+)u,0x([0-9A-F]+)u\},$'){
            $first=[Convert]::ToInt32($Matches[1],16);$last=[Convert]::ToInt32($Matches[2],16)
            [Array]::Fill($actual,[byte]$class,$first,$last-$first+1)
        }
    }
    for($index=0;$index -lt $expected.Length;++$index){
        if($actual[$index] -ne $expected[$index]){throw ('Bidi class differs at U+{0:X}' -f $index)}
    }
    Assert-Equal ([byte]1) $actual[0x0378] 'unassigned ordinary scalar defaults L'
    Assert-Equal ([byte]2) $actual[0x0590] 'unassigned Hebrew scalar defaults R'
    Assert-Equal ([byte]0) $actual[0x20c2] 'unassigned currency scalar defaults ET'
    Assert-Equal ([byte]0) $actual[0xfdd0] 'explicit BN noncharacter overrides L default'
}
