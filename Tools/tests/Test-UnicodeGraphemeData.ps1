# Offline reproducibility and fail-closed provenance for the shared Unicode tables.
[CmdletBinding()] param()
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'TestSupport.psm1') -Force
$repository = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$generator = Join-Path $repository 'Tools/Generate-UnicodeGraphemeData.ps1'
$inputs = Join-Path $repository 'ThirdParty/Unicode/17.0.0'
$outputs = @('DxUi.TextElementsData.h', 'Scope.Tests.UnicodeGraphemeCorpus.h')

Invoke-FixtureCase 'the pinned inputs regenerate both checked-in headers byte for byte without network access' {
    param($root)
    & $generator -InputDirectory $inputs -OutputDirectory $root
    $canonical = @('src/Controls/DxUi.TextElementsData.h', 'Tests/Controls/Scope.Tests.UnicodeGraphemeCorpus.h')
    for ($index = 0; $index -lt $outputs.Count; ++$index) {
        Assert-Equal (Get-FileHash -LiteralPath (Join-Path $repository $canonical[$index])).Hash `
            (Get-FileHash -LiteralPath (Join-Path $root $outputs[$index])).Hash 'generated bytes match the committed header'
    }
    $before = @($outputs | ForEach-Object { (Get-FileHash -LiteralPath (Join-Path $root $_)).Hash }) -join ','
    & $generator -InputDirectory $inputs -OutputDirectory $root
    Assert-Equal $before (@($outputs | ForEach-Object { (Get-FileHash -LiteralPath (Join-Path $root $_)).Hash }) -join ',') 'a second generation is deterministic'
}

Invoke-FixtureCase 'check mode accepts generated data and does not rewrite either file' {
    param($root)
    & $generator -InputDirectory $inputs -OutputDirectory $root
    $old = [DateTime]::new(2020, 1, 1, 0, 0, 0, [DateTimeKind]::Utc)
    foreach ($name in $outputs) { [IO.File]::SetLastWriteTimeUtc((Join-Path $root $name), $old) }
    & $generator -InputDirectory $inputs -OutputDirectory $root -Check
    foreach ($name in $outputs) { Assert-Equal $old ([IO.File]::GetLastWriteTimeUtc((Join-Path $root $name))) 'verification is read only' }
}

Invoke-FixtureCase 'check mode rejects missing and stale outputs without repairing or creating them' {
    param($root)
    Assert-Throws { & $generator -InputDirectory $inputs -OutputDirectory $root -Check } 'missing generated output fails'
    Assert-Equal 0 @(Get-ChildItem -LiteralPath $root).Count 'check mode creates no missing output'
    & $generator -InputDirectory $inputs -OutputDirectory $root
    foreach ($name in $outputs) {
        $path = Join-Path $root $name
        $original = [IO.File]::ReadAllBytes($path)
        [IO.File]::AppendAllText($path, '// stale')
        $changed = (Get-FileHash -LiteralPath $path).Hash
        Assert-Throws { & $generator -InputDirectory $inputs -OutputDirectory $root -Check } "stale $name fails"
        Assert-Equal $changed (Get-FileHash -LiteralPath $path).Hash 'failure leaves the stale evidence untouched'
        [IO.File]::WriteAllBytes($path, $original)
    }
}

Invoke-FixtureCase 'every data and license pin is mandatory and checked before any output is written' {
    param($root)
    $copiedInputs = Join-Path $root 'inputs'
    New-Item -ItemType Directory -Path $copiedInputs | Out-Null
    $target = Join-Path $root 'output'
    foreach ($name in @('GraphemeBreakProperty.txt', 'GraphemeBreakTest.txt', 'DerivedCoreProperties.txt', 'emoji-data.txt', 'LICENSE.txt')) {
        Copy-Item -LiteralPath (Join-Path $inputs $name) -Destination $copiedInputs
    }
    foreach ($name in @('GraphemeBreakProperty.txt', 'GraphemeBreakTest.txt', 'DerivedCoreProperties.txt', 'emoji-data.txt', 'LICENSE.txt')) {
        $path = Join-Path $copiedInputs $name
        $original = [IO.File]::ReadAllBytes($path)
        [IO.File]::AppendAllText($path, ' ')
        Assert-Throws { & $generator -InputDirectory $copiedInputs -OutputDirectory $target } "changed $name fails"
        Assert-True (-not (Test-Path -LiteralPath $target)) 'a refused input creates no generated output'
        [IO.File]::WriteAllBytes($path, $original)
        # A rename within the verified fixture also exercises a missing input.
        Move-Item -LiteralPath $path -Destination ($path + '.held')
        try { Assert-Throws { & $generator -InputDirectory $copiedInputs -OutputDirectory $target } "missing $name fails" }
        finally { Move-Item -LiteralPath ($path + '.held') -Destination $path }
        Assert-True (-not (Test-Path -LiteralPath $target)) 'a missing input creates no generated output'
    }
}

Complete-TestRun 'Unicode grapheme generation'
