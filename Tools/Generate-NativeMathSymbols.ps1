<#
.SYNOPSIS Generates bounded native math symbols from the pinned KaTeX symbol source.
.DESCRIPTION Admits explicit one-codepoint, alphabetic control words with TeX atom classes. Operators, accents,
spacing, dynamic definitions, macros and non-BMP replacements remain owned by the separate native grammar.
.PARAMETER InputDirectory Directory holding the pinned KaTeX source.
.PARAMETER OutputPath Generated C++ header.
.PARAMETER Check Checks exact generated bytes without writing.
.OUTPUTS Generated header unless Check is selected. No network or temporary files.
.EXAMPLE
./Tools/Generate-NativeMathSymbols.ps1 -Check
#>
[CmdletBinding()]
param([string]$InputDirectory=(Join-Path $PSScriptRoot '../ThirdParty/Markdown/katex-0.16.11'),
      [string]$OutputPath=(Join-Path $PSScriptRoot '../src/Controls/DxUi.NativeMathSymbols.h'),[switch]$Check)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
$source=Join-Path $InputDirectory 'symbols.js.txt'
if ((Get-FileHash -LiteralPath (Join-Path $InputDirectory 'LICENSE.txt') -Algorithm SHA256).Hash -cne '766CCC1F306C885AA45542A9846BBD0A505B27A0374F146778171C2254CE18E3') {throw 'Pinned KaTeX license differs.'}
if((Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash -cne 'B868D9461CD60C21DCD29BB1829389783C2864714C3E5B7D053EF0CECCECF511') {throw 'Pinned KaTeX symbols source differs.'}
$classes=@{ bin='Binary';close='Closing';inner='Inner';mathord='Ordinary';open='Opening';punct='Punctuation';rel='Relation';textord='Ordinary' }
$entries=[Collections.Generic.Dictionary[string,object]]::new([StringComparer]::Ordinal)
$pattern='^defineSymbol\(math,\s*(?:main|ams),\s*(bin|close|inner|mathord|open|punct|rel|textord),\s*"\\u([0-9a-fA-F]{4})",\s*"\\\\([A-Za-z]+)"'
foreach($line in [IO.File]::ReadLines($source)) {
    if($line -cmatch $pattern) {
        $group=$Matches[1];$code=$Matches[2].ToUpperInvariant();$name=$Matches[3]
        # The four vertical delimiter commands retain the native paired-delimiter glyph contract.
        if ($name -cin @('lvert','rvert','lVert','rVert')) { continue }
        $scalar=[Convert]::ToInt32($code,16)
        if($scalar -ge 0xD800 -and $scalar -le 0xDFFF){throw "Unpaired surrogate in $name"}
        if($entries.ContainsKey($name)){throw "Duplicate symbol command $name"}
        $entries[$name]=@{class=$classes[$group];code=$code;italic=($group -eq 'mathord')}
    }
}
if($entries.Count -ne 411){throw "Expected 411 explicit native symbols, got $($entries.Count)"}
$names=[string[]]@($entries.Keys);[Array]::Sort($names,[StringComparer]::Ordinal)
$output=[Text.StringBuilder]::new()
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <DxUi/RichMath.h>')
[void]$output.AppendLine('#include <string_view>')
[void]$output.AppendLine('// Generated from pinned KaTeX 0.16.11 symbols.js; explicit one-codepoint commands only.')
[void]$output.AppendLine('namespace DxUi::RichText::Detail')
[void]$output.AppendLine('{')
[void]$output.AppendLine('// clang-format off')
[void]$output.AppendLine('struct NativeMathSymbol { std::wstring_view name; wchar_t glyph; MathAtomClass atom; bool italic; };')
[void]$output.AppendLine('inline constexpr NativeMathSymbol NativeMathSymbols[] = {')
foreach($name in $names){$v=$entries[$name];$italic=if($v.italic){'true'}else{'false'};[void]$output.AppendLine(('    {{L"{0}", L''\x{1}'', MathAtomClass::{2}, {3}}},' -f $name,$v.code,$v.class,$italic))}
[void]$output.AppendLine('};')
[void]$output.AppendLine('// clang-format on')
[void]$output.AppendLine('} // namespace DxUi::RichText::Detail')
$expected=$output.ToString().Replace("`r`n","`n").Replace("`n","`r`n")
if($Check){if(-not(Test-Path -LiteralPath $OutputPath) -or [IO.File]::ReadAllText($OutputPath) -cne $expected){throw 'Native math symbol header is missing or stale.'}}
else{[IO.File]::WriteAllText($OutputPath,$expected,[Text.UTF8Encoding]::new($false))}
Write-Host "Native math symbols: $($entries.Count) pinned one-codepoint commands."
